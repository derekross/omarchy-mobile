#!/usr/bin/env python3
# Tactus's word pairs: which word follows which, counted in Tatoeba's English
# sentences, for the autocorrection's sense of context.
#
#   tactus-word-pairs.py eng_sentences.tsv.bz2 > word-pairs.txt
#   tactus-word-pairs.py --held-out FILE eng_sentences.tsv.bz2 > word-pairs.txt
#
# The input is Tatoeba's weekly export of its English sentences
# (https://downloads.tatoeba.org/exports/per_language/eng/eng_sentences.tsv.bz2,
# CC BY 2.0 FR). Every twentieth sentence (by its number) is left out of the
# counts, so that the checks can type sentences the counts have not seen;
# --held-out writes those to FILE (for the checks only: never shipped).
#
# A word is its letters, small, without apostrophes ("don't" is "dont"), as
# the autocorrection sees what is typed. Two words are a pair only when a
# space alone stands between them; "^" stands for the start of a sentence.
#
# Copyright (C) 2026 W4HO
#
# SPDX-License-Identifier: GPL-3.0-or-later

import bz2
import collections
import re
import sys

WORDS = 10000  # the commonest words that are kept
LEAST = 6      # how often a pair is seen before it is kept

TOKEN = re.compile(r"^([\"'(\[]*)([A-Za-z]+(?:'[A-Za-z]+)*)([^A-Za-z]*)$")


def main(argv):
    held_out = None
    if len(argv) >= 3 and argv[1] == '--held-out':
        held_out = open(argv[2], 'w', encoding='utf-8')
        argv = [argv[0]] + argv[3:]
    if len(argv) != 2:
        sys.exit('usage: tactus-word-pairs.py [--held-out FILE] eng_sentences.tsv.bz2')

    words = collections.Counter()
    pairs = collections.Counter()
    total = 0
    sentences = 0
    with bz2.open(argv[1], 'rt', encoding='utf-8') as f:
        for line in f:
            parts = line.rstrip('\n').split('\t')
            if len(parts) < 3 or not parts[0].isdigit():
                continue
            if int(parts[0]) % 20 == 0:
                if held_out:
                    held_out.write(parts[2] + '\n')
                continue
            sentences += 1
            prev = '^'
            for raw in parts[2].split():
                m = TOKEN.match(raw)
                if not m:
                    prev = None
                    continue
                word = m.group(2).replace("'", '').lower()
                if m.group(1):
                    prev = None
                words[word] += 1
                total += 1
                if prev is not None:
                    pairs[(prev, word)] += 1
                trail = m.group(3)
                prev = '^' if trail[:1] in ('.', '!', '?') else (None if trail else word)

    kept = [w for w, _ in sorted(words.items(), key=lambda wc: (-wc[1], wc[0]))[:WORDS]]
    keep = set(kept) | {'^'}
    after = collections.defaultdict(list)
    for (a, b), c in pairs.items():
        if c >= LEAST and a in keep and b in keep:
            after[a].append((b, c))

    out = sys.stdout
    out.write('# Tactus word pairs: generated by tools/tactus-word-pairs.py from Tatoeba\'s\n')
    out.write('# English sentences (https://tatoeba.org, CC BY 2.0 FR). See WORD-PAIRS.\n')
    out.write('total %d\n' % total)
    out.write('sentences %d\n' % sentences)
    out.write('words\n')
    for w in kept:
        out.write('%s %d\n' % (w, words[w]))
    out.write('pairs\n')
    for a in ['^'] + sorted(keep - {'^'}):
        if after.get(a):
            out.write(a + ' ' + ' '.join('%s:%d' % bc for bc in sorted(after[a])) + '\n')


if __name__ == '__main__':
    main(sys.argv)
