"""Generate a Pixel 9a (tegu) fuel-gauge model overlay from Google's tegu battery devicetree.

Usage: gen-gauge-overlay-tegu.py [--raw] SOURCE NODE OUT.dtso

  SOURCE  Google's public, GPL-2.0-only dts/zuma-tegu-battery-data.dtsi (kernel/devices/google/
          tegu, branch android-gs-tegu-6.1-android16), the file with the
          "max77779,<NODE> { max77779,fg-model ... max77779,fg-params ... }" nodes.
  NODE    the model node: lwn-4k (pack ID 4) or atl-1k (pack ID 1).
  --raw   write the node's parameters as they are. Without it, nFullSOCThr and nMiscCfg are
          the values Google's driver writes at a model load: max77779_model_apply_aaf_fullsoc()
          (max77779_fg_model.c) replaces them from the node's max77779,fg-aafv row 0
          (aafv_cur_idx is 0 after a power-on reset): nFullSOCThr = fullsoc << 8 and
          nMiscCfg = (nMiscCfg & ~0xf000) | (fus << 12), kept to 16 bits as in that u16.

Writes maxim,fg-model (32 u16) and maxim,fg-params (22 u16, in the order of Google's
struct max77779_custom_parameters). Nothing is typed by hand, in the manner of
tools/gen-gauge-overlay.py for husky."""
import re
import sys

PARAM_NAMES = ["nNVCfg0", "RelaxCFG", "nLearnCFG", "Config", "Config2", "nFullSOCthr",
               "nFullCAPRep", "nDesignCap", "dPacc", "nFullCAPNom", "nV_empty", "nQRTable00",
               "nQRTable10", "nQRTable20", "nQRTable30", "nRCOMP0", "nTempCo", "nIChgTerm",
               "nMiscCFG", "nModelCfg", "nThermCfg", "nFilterCfg"]
I_FULLSOC, I_MISC = PARAM_NAMES.index("nFullSOCthr"), PARAM_NAMES.index("nMiscCFG")
URL = ("https://android.googlesource.com/kernel/devices/google/tegu/+/refs/heads/"
       "android-gs-tegu-6.1-android16/dts/zuma-tegu-battery-data.dtsi")


def strip_comments(text):
    text = re.sub(r'/\*.*?\*/', ' ', text, flags=re.S)
    return re.sub(r'//[^\n]*', '', text)


def cells(prop, body, bits):
    m = re.search(r'max77779,' + re.escape(prop) + r'\s*=\s*/bits/\s*' + bits + r'\s*<([^>]*)>', body)
    if not m:
        sys.exit(f"no max77779,{prop} (/bits/ {bits}) in the node")
    return [int(x, 0) for x in m.group(1).split()]


def read_node(text, node):
    text = strip_comments(text)
    # Limit: the node body ends at the first line holding only '};' (no nested nodes).
    m = re.search(r'max77779,' + re.escape(node) + r'\s*\{(.*?)\n\s*\};', text, re.S)
    if not m:
        sys.exit(f"no max77779,{node} node in the source")
    body = m.group(1)
    model, params = cells("fg-model", body, "16"), cells("fg-params", body, "16")
    aafv = cells("fg-aafv", body, "32")
    if len(model) != 32:
        sys.exit(f"{node}: fg-model has {len(model)} words, expected 32")
    if len(params) != 22:
        sys.exit(f"{node}: fg-params has {len(params)} words, expected 22")
    if len(aafv) % 4 or not aafv:
        sys.exit(f"{node}: fg-aafv is not rows of four")
    kohm = re.search(r'max77779,batt-id-kohm\s*=\s*<\s*(\w+)\s*>', body)
    ver = re.search(r'max77779,model-version\s*=\s*<\s*(\w+)\s*>', body)
    return model, params, aafv[:4], int(kohm.group(1), 0), int(ver.group(1), 0)


def fmt(ws):
    return "\n".join("\t\t" + " ".join("0x%04x" % w for w in ws[i:i + 8]) for i in range(0, len(ws), 8))


def render(node, model, params, raw, note, kohm, ver):
    return f"""// SPDX-License-Identifier: GPL-2.0-only
/*
 * Bring-up overlay, never default: load Google's ModelGauge m5 model "{node}"
 * (battery ID {kohm}, model version {ver}) into the Pixel 9a's MAX77779 fuel gauge after
 * a power-on reset. Google's driver picks the node by the pack's ID, byte 0x17
 * of its EEPROM: 1 atl-1k, 4 lwn-4k. Generated by gen-gauge-overlay-tegu.py from
 * Google's public, GPL-2.0-only dts/zuma-tegu-battery-data.dtsi
 * (kernel/devices/google/tegu, branch android-gs-tegu-6.1-android16,
 * {URL}):
 * maxim,fg-model = that node's 32 u16 table words, maxim,fg-params = its 22
 * parameter words in the order of Google's struct max77779_custom_parameters.
 * {note}
 * The driver loads it only while the gauge reports power-on reset (Status
 * bit 1), then clears that bit. The table and the parameters are Copyright
 * 2024 Google LLC, from that file.
 *
 * Which pack: our device tree doesn't describe the pack's EEPROM, so read the
 * size while stock's model is still in the gauge, before the first load of
 * an overlay: charge_full_design reads 5110000 on an ATL pack and 5120000 on
 * an LWN pack. A wrong model stays in the gauge until its next power-on
 * reset, which takes a flat pack, and until then the charge follows the
 * other pack's curve. After a load the gauge counts cycles from the reset:
 * cycle_count, and the battery panel's charge cycles, read 0 for an old
 * pack: Google's driver keeps the pack's own count in that EEPROM.
 */
/dts-v1/;
/plugin/;

&fuel_gauge {{
	maxim,fg-model = /bits/ 16 <
{fmt(model)}
	>;
	maxim,fg-params = /bits/ 16 <
{fmt(params)}
	>;
}};
"""


args = sys.argv[1:]
raw = "--raw" in args
args = [a for a in args if a != "--raw"]
if len(args) != 3:
    sys.exit(__doc__)
src, node, out = args
model, params, aafv0, kohm, ver = read_node(open(src).read(), node)
orig = list(params)
if raw:
    note = "Parameters as in the node (--raw)."
else:
    _, _, fullsoc, fus = aafv0
    params[I_FULLSOC] = (fullsoc << 8) & 0xffff
    params[I_MISC] = ((params[I_MISC] & ~0xf000) | (fus << 12)) & 0xffff
    note = ("nFullSOCThr and nMiscCfg as Google's driver writes them at a load, from\n"
            f" * max77779,fg-aafv row 0 ({' '.join(str(x) if i < 3 else hex(x) for i, x in enumerate(aafv0))}): "
            f"{orig[I_FULLSOC]:#06x} -> {params[I_FULLSOC]:#06x},\n"
            f" * {orig[I_MISC]:#06x} -> {params[I_MISC]:#06x} (max77779_model_apply_aaf_fullsoc()).")
open(out, "w").write(render(node, model, params, raw, note, kohm, ver))
print(f"{node}: ID {kohm}, version {ver}, model words {len(model)}, param words {len(params)},"
      f" nDesignCap {params[7]:#06x} ({params[7] * 5 // 2} mAh at 2 mOhm), dPAcc {params[8]:#06x},"
      f" nFullSOCThr {orig[I_FULLSOC]:#06x}->{params[I_FULLSOC]:#06x},"
      f" nMiscCfg {orig[I_MISC]:#06x}->{params[I_MISC]:#06x}")
